/*************************************************
* Name:        ntt_naive
**************************************************/
void ntt_naive(int32_t r[1152]) {
  unsigned int len, start, j, k;
  int32_t t, zeta;
  int32_t tb, tc, tpho, zeta1, zeta2;

  // Radix-2
  k = 1;
  for(len = 576; len >= 9; len >>= 1) {
    for(start = 0; start < 1152; start = j + len) {
      zeta = zetas[k++];
      for(j = start; j < start + len; j++) {
        t = fQmul(zeta, r[j + len]);
        r[j + len] = r[j] - t;
        r[j] = r[j] + t;
      }
    }
  }
  
  // Radix-3
  len = 3;
  for (start = 0; start < 1152; start += 3 * len)
  {
    zeta1 = zetas[k++];
    zeta2 = zetas[k++];
    for (j = start; j < start + len; j++)
    {
      tb = fQmul(zeta1, r[j + len]);
      tc = fQmul(zeta2, r[j + len + len]);
      tpho = fQmul(ROOT_3, tb - tc);

      r[j + len + len] = r[j] - tb - tpho;
      r[j + len] = r[j] - tc + tpho;
      r[j] = r[j] + tb + tc;
    }
  }

  // Radix-3
  len = 1;
  for (start = 0; start < 1152; start += 3 * len)
  {
    zeta1 = zetas[k++];
    zeta2 = zetas[k++];
    for (j = start; j < start + len; j++)
    {
      tb = fQmul(zeta1, r[j + len]);
      tc = fQmul(zeta2, r[j + len + len]);
      tpho = fQmul(ROOT_3, tb - tc);

      r[j + len + len] = r[j] - tb - tpho;
      r[j + len] = r[j] - tc + tpho;
      r[j] = r[j] + tb + tc;
    }
  }
}

/*************************************************
* Name:        invtntt_naive
**************************************************/
void invtntt_naive(int32_t r[1152]) {
  unsigned int start, len, j, k;
  int32_t t, zeta;
  int32_t tb, tc, tpho, zeta1, zeta2;

  k = 0;

  // Radix-3
  len = 1;
  for (start = 0; start < 1152; start += 3 * len)
  {
    zeta1 = zetas_inv[k++];
    zeta2 = zetas_inv[k++];
    for (j = start; j < start + len; j++)
    {
      tpho = fQmul(ROOT_3, r[j + len] - r[j + len + len]);
      tb = (r[j] - r[j + len] - tpho);
      tc = (r[j] - r[j + len + len] + tpho);

      r[j] = (r[j] + r[j + len] + r[j + len + len]);
      r[j + len] = fQmul(zeta1, tb);
      r[j + len + len] = fQmul(zeta2, tc);
    }
  }

  // Radix-3
  len = 3;
  for (start = 0; start < 1152; start += 3 * len)
  {
    zeta1 = zetas_inv[k++];
    zeta2 = zetas_inv[k++];
    for (j = start; j < start + len; j++)
    {
      tpho = fQmul(ROOT_3, r[j + len] - r[j + len + len]);
      tb = (r[j] - r[j + len] - tpho);
      tc = (r[j] - r[j + len + len] + tpho);

      r[j] = (r[j] + r[j + len] + r[j + len + len]);
      r[j + len] = fQmul(zeta1, tb);
      r[j + len + len] = fQmul(zeta2, tc);
    }
  }
  
  // Radix-2
  for(len = 9; len <= 576; len <<= 1) {
    for(start = 0; start < 1152; start = j + len) {
      zeta = zetas_inv[k++];
      for(j = start; j < start + len; j++) {
        t = r[j];
        r[j] = t + r[j + len];
        r[j + len] = t - r[j + len];
        r[j + len] = fQmul(zeta, r[j + len]);
      }
    }
  }

  for(j = 0; j < 576; j++)
    r[j] = fQmul(r[j], zetas_inv[1151]);
}



/*************************************************
* Name:        poly_pointwise
**************************************************/
void poly_pointwise(int32_t c[1152], const int32_t a[1152], const int32_t b[1152])
{
  unsigned int i;
  for(i = 0; i < 1152; ++i)
    c[i] = fQmul(a[i], b[i]);
}

/*************************************************
* Name:        poly_reduction
**************************************************/
void poly_reduction(int16_t r[571], const int32_t a[1152])
{
    unsigned int i;
    int32_t tmp[571];

    tmp[0] = a[0] + a[571];
    for(i = 1; i < 570; i++)
      tmp[i] = a[i + 570] + a[i + 571] + a[i];
    tmp[570] = a[570] + a[1140];

    for(i = 0; i < 571; ++i)
      r[i] = reduce32to16(tmp[i]); 
}

/*************************************************
* Name:        poly_padding
**************************************************/
void poly_padding(int32_t r[1152], const int16_t a[571])
{
  unsigned int i;
  for(i=0;i<571;i++){
    r[i]=a[i];
  }
  for(i=571;i<1152;i++){
    r[i]=0;
  }

}
